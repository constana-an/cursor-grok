  bucket_id = 'memory-photos' and exists (
    select 1 from public.profiles p where p.user_id = auth.uid() and p.couple_id::text = (storage.foldername(name))[1]
  )
);
drop policy if exists "couple memory photo upload" on storage.objects;
create policy "couple memory photo upload" on storage.objects for insert with check (
  bucket_id = 'memory-photos' and exists (
    select 1 from public.profiles p where p.user_id = auth.uid() and p.couple_id::text = (storage.foldername(name))[1]
  )
);
