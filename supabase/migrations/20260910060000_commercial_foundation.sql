create or replace function public.create_couple_space(display_name text)
returns table(couple_id uuid, invite_code text)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_couple_id uuid;
  v_invite_code text;
begin
  if auth.uid() is null then raise exception 'not authenticated'; end if;
  if coalesce((auth.jwt() ->> 'is_anonymous')::boolean, false) then raise exception 'permanent account required'; end if;
  perform public.assert_action_limit('create_space', 3, 60);
  if exists (select 1 from public.profiles where user_id = auth.uid()) then raise exception 'already paired'; end if;
  loop
    v_invite_code := lpad((floor(random() * 900000) + 100000)::text, 6, '0');
    begin
      insert into public.couples(invite_code) values (v_invite_code) returning id into v_couple_id;
      exit;
    exception when unique_violation then null;
    end;
  end loop;
  insert into public.profiles(user_id, couple_id, display_name) values (auth.uid(), v_couple_id, display_name);
  insert into public.memberships(couple_id, plan_id) values (v_couple_id, 'free') on conflict do nothing;
  perform public.write_audit(v_couple_id, 'couple.created', jsonb_build_object('identity', display_name));
  return query select v_couple_id, v_invite_code;
end;
$$;

create or replace function public.join_couple_space(code text, display_name text)
returns table(couple_id uuid)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_couple_id uuid;
begin
  if auth.uid() is null then raise exception 'not authenticated'; end if;
  if coalesce((auth.jwt() ->> 'is_anonymous')::boolean, false) then raise exception 'permanent account required'; end if;
  perform public.assert_action_limit('join_space', 10, 60);
  if exists (select 1 from public.profiles where user_id = auth.uid()) then raise exception 'already paired'; end if;
  select id into v_couple_id from public.couples where invite_code = trim(code);
  if v_couple_id is null then raise exception 'invalid invite code'; end if;
  if (select count(*) from public.profiles where couple_id = v_couple_id) >= 2 then raise exception 'couple space is full'; end if;
  insert into public.profiles(user_id, couple_id, display_name) values (auth.uid(), v_couple_id, display_name);
  insert into public.memberships(couple_id, plan_id) values (v_couple_id, 'free') on conflict do nothing;
  perform public.write_audit(v_couple_id, 'couple.joined', jsonb_build_object('identity', display_name));
  return query select v_couple_id;
end;
