create or replace function public.update_order_status(p_order_id uuid, p_status text)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
begin
  if p_status not in ('accepted','doing','done','rejected') then raise exception 'invalid status'; end if;
  perform public.assert_action_limit('update_order', 30, 10);
  select o.* into v_order from public.orders o join public.profiles p on p.couple_id = o.couple_id
  where o.id = p_order_id and p.user_id = auth.uid();
  if v_order.id is null then raise exception 'order not found'; end if;
  if not ((v_order.status = 'pending' and p_status in ('accepted','rejected')) or (v_order.status = 'accepted' and p_status = 'doing') or (v_order.status = 'doing' and p_status = 'done')) then
    raise exception 'invalid transition';
  end if;
  update public.orders set status = p_status where id = p_order_id;
  perform public.write_audit(v_order.couple_id, 'order.status_changed', jsonb_build_object('order_id', p_order_id, 'from', v_order.status, 'to', p_status));
  return p_status;
end;
$$;

