/**
 * Chinese and English copy for every piece of app chrome.
 *
 * What is translated and what is not is a deliberate line:
 *
 * - App chrome, and the shop's own built-in catalogue (menu, tasks, prompts,
 *   milestones), are translated here and in `catalog.ts`.
 * - Everything the couple typed themselves — shop name, their two names, custom
 *   wishes, order notes, memory captions, anniversary titles — is never
 *   touched. Rewriting a person's own words in another language would be a lie
 *   about what they wrote.
 * - Order rows keep whatever was stored when the order was placed. Built-in
 *   items are re-localised for display through their `itemId` (see
 *   `localizedItemName`), so a couple reading in two different languages still
 *   sees the same order named correctly on each phone.
 *
 * `zh` defines the key set; TypeScript requires `en` to answer for every one of
 * them, so a new string cannot be added in one language only.
 */

export type Lang = "zh" | "en";

export const LANGS: Lang[] = ["zh", "en"];

/** Each language names itself, so the switch is readable in either mode. */
export const LANG_LABEL: Record<Lang, string> = { zh: "中文", en: "English" };

export const LANG_STORAGE_KEY = "couple-shop-lang";

/**
 * English is what a device opens in. Nothing is guessed from
 * `navigator.language`: a silent switch on a device that has already been set
 * up would rename half the screen without being asked, so the only thing that
 * ever changes the language is somebody tapping the switch.
 *
 * `zh` still defines the key set below, because the copy was written in Chinese
 * first. Which language is authored first and which one a device opens in are
 * two different decisions, and only the second one is this constant.
 */
export const DEFAULT_LANG: Lang = "en";

export const isLang = (value: unknown): value is Lang => value === "zh" || value === "en";

export function loadLang(): Lang {
  try {
    const saved = localStorage.getItem(LANG_STORAGE_KEY);
    return isLang(saved) ? saved : DEFAULT_LANG;
  } catch {
    return DEFAULT_LANG;
  }
}

export function saveLang(lang: Lang): void {
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch {
    // A blocked storage must not stop the language from changing on screen.
  }
}

/** What belongs in `<html lang>` and in `Intl` lookups. */
export const localeOf = (lang: Lang): string => (lang === "zh" ? "zh-CN" : "en-US");

