export const STRINGS: Record<Lang, Record<TKey, string>> = { zh, en };

export type TVars = Record<string, string | number>;

/**
 * Two placeholder forms:
 *
 * - `{name}` is replaced by that variable.
 * - `{name#one#many}` picks a word to agree with the *number* in `name`, which
 *   is what stops an English screen saying "1 wishes to go". Chinese never
 *   needs it, so its side of the dictionary simply never writes one.
 *
 * Anything with no matching variable is left exactly as it was written, so a
 * missing value shows up as an obvious `{name}` rather than as "undefined".
 */
export function translate(lang: Lang, key: TKey, vars?: TVars): string {
  const template = STRINGS[lang][key] ?? STRINGS[DEFAULT_LANG][key] ?? key;
  if (!vars) return template;
  return template
    .replace(/\{(\w+)#([^#{}]*)#([^#{}]*)\}/g, (match, name: string, one: string, many: string) => {
      if (!(name in vars)) return match;
      return Math.abs(Number(vars[name])) === 1 ? one : many;
    })
    .replace(/\{(\w+)\}/g, (match, name: string) =>
      (name in vars ? String(vars[name]) : match));
}

export type TFunction = (key: TKey, vars?: TVars) => string;

/** A translator bound to one language, for code outside a React component. */
export const translatorFor = (lang: Lang): TFunction => (key, vars) => translate(lang, key, vars);
